        proxy_pass http://127.0.0.1:8008;
    }
    location /_synapse/client {
        include snippets/matrix-proxy.conf;
        proxy_pass http://127.0.0.1:8008;
    }
    # Admin API (edge proxy restricts to private IPs)
    location /_synapse/admin {
        include snippets/matrix-proxy.conf;
        proxy_pass http://127.0.0.1:8008;
    }

