# Public traffic arrives from the edge proxy over HTTPS with the original Host header.

# Plain HTTP: redirect everything to HTTPS.
server {
    listen 80 default_server;
    listen [::]:80 default_server;
    server_name _;
    return 301 https://$host$request_uri;
}

