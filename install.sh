    elif [ -z "$RENDER_DIR" ]; then
        rm -f /etc/matrix-synapse/conf.d/federation.yaml
    fi
    put /etc/matrix-synapse/appservices/lk-jwt-service.yaml 640 matrix-synapse:lk-jwt <<'EOF'
