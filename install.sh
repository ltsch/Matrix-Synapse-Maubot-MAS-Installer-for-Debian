$synapse_up || die "Synapse did not become healthy within 2 minutes (journalctl -u matrix-synapse -n 50); fix and re-run install.sh"
(cd /opt/mas && sudo -u mas MAS_CONFIG=/opt/mas/config.yaml /opt/mas/mas manage register-user "$ADMIN_USER" \
    --password "$ADMIN_PASS" --admin --yes --ignore-password-complexity) \
    || warn "admin user not created (it may already exist from an earlier attempt)"
systemctl enable --now livekit lk-jwt-service maubot mas-invite coturn nginx
systemctl restart coturn nginx

log "Scheduled jobs (systemd timers)"
for f in matrix_monitor update_turn_ip refresh_certs matrix_backup; do
    install -m 640 -o root -g adm /dev/null "/var/log/$f.log"
done
# Drop cron entries left by older versions of this project.
if crontab -l >/dev/null 2>&1; then
    crontab -l | grep -v -e refresh_certs.sh -e monitor_services.sh -e update_turn_ip.sh -e backup_matrix.sh \
        | crontab - || true
fi
systemctl enable --now matrix-turn-ip.timer matrix-monitor.timer
if [ -f "$HERE/refresh_certs.conf" ]; then
    systemctl enable --now matrix-refresh-certs.timer
    "$HERE/refresh_certs.sh" || warn "refresh_certs.sh failed - nginx is using a self-signed placeholder cert (see output above)"
else
    warn "refresh_certs.conf missing - nginx is using a self-signed placeholder cert;" \
         "matrix-refresh-certs.timer left disabled (create the file, then: systemctl enable --now matrix-refresh-certs.timer)"
fi

umask 077
cat > /root/matrix_credentials.txt <<EOF
Matrix installation credentials - $(date -Is)
Homeserver:      https://$MATRIX_FQDN   (auth: https://$AUTH_FQDN)
Admin user:      @$ADMIN_USER:$MATRIX_FQDN
Admin password:  $ADMIN_PASS
Maubot UI:       https://$MATRIX_FQDN/_matrix/maubot   user: admin  password: $MAUBOT_ADMIN_PASS
(Database passwords and service secrets are in the service config files.)
EOF

rm -f "$SECRETS_FILE"   # install complete; secrets now live in the service configs
log "Done. Credentials: /root/matrix_credentials.txt"
log "Next: configure the edge proxy and firewall (docs/INSTALL.md), then run ./upgrade_services.sh --check."
