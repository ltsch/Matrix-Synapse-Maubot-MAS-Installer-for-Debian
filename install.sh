    listen 443 ssl default_server;
    listen [::]:443 ssl default_server;
    server_name ${MATRIX_FQDN};

    ssl_certificate     /etc/nginx/ssl/matrix.crt;
    ssl_certificate_key /etc/nginx/ssl/matrix.key;

