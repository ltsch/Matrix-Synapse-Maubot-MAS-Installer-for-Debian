public_baseurl: https://${MATRIX_FQDN}/
pid_file: "/var/run/matrix-synapse.pid"

# Plain HTTP on localhost only; nginx (behind the edge proxy) terminates TLS.
listeners:
  - port: 8008
    bind_addresses: ['127.0.0.1']
    type: http
    tls: false
    x_forwarded: true
    resources:
      - names: [client, federation]
        compress: false

